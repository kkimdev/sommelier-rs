//! Plain geometry that more than one concern shares, owned by none of
//! them.

/// An integer rectangle in logical screen coordinates.
///
/// An output's work area, and the window bounds a placement maps into it.
/// It is plain data: a value with a non-positive extent is representable,
/// and `window_layout::NormalizedRect::to_work_area_bounds` rejects it as a
/// work area.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct Rect {
    pub x: i32,
    pub y: i32,
    pub width: i32,
    pub height: i32,
}

impl Rect {
    /// Build a rectangle from its origin and extent.
    pub(crate) const fn new(x: i32, y: i32, width: i32, height: i32) -> Self {
        Self {
            x,
            y,
            width,
            height,
        }
    }
}
