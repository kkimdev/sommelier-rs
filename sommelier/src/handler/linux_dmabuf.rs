/// Whether `event` of params the guest destroyed still reaches its handler
/// (`handler::outlives_destroy`): an asynchronous create's `created`, which
/// may legally follow `destroy`. The host still owns a newly created
/// `wl_buffer` then, which `on_created` destroys; dropping the event would
/// leak it, since the generated `new_id` mapping only runs when the event
/// is forwarded. A `failed` needs nothing: it discards what the create
/// kept, and the params' destructor discards that too.
pub(crate) fn outlives_destroy(event: &zwp_linux_buffer_params_v1::Event) -> bool {
    matches!(event, zwp_linux_buffer_params_v1::Event::Created { .. })
}

impl zwp_linux_dmabuf_v1::ZwpLinuxDmabufV1Handler for Handlers {
    fn on_create_params(ctx: &mut Context, _sender: RequestSender, params_id: GuestId) -> Action {
        ctx.defer_until_forwarded(PostDispatch::Attach {
            object: params_id,
            data: ParamsData::Open(Vec::new()).into(),
        });
        Action::Forward
    }

    fn on_get_default_feedback(ctx: &mut Context, sender: RequestSender, id: GuestId) -> Action {
        create_synthetic_feedback(ctx, sender.guest, id)
    }

    fn on_get_surface_feedback(
        ctx: &mut Context,
        sender: RequestSender,
        id: GuestId,
        _surface: RequestObject,
    ) -> Action {
        create_synthetic_feedback(ctx, sender.guest, id)
    }

    fn on_format(ctx: &mut Context, sender: EventSender, format: u32) -> Action {
        if !is_supported_drm_format(format) {
            return Action::Drop;
        }
        if record_host_capability(ctx, sender.host, format, DRM_FORMAT_MOD_INVALID) {
            return Action::Drop;
        }

        // A synthetic v4 factory is backed by a v3 host object so create_params
        // remains forwardable. Do not leak the host's deprecated legacy events
        // to a guest that bound the v4 contract.
        if sender
            .guest_id()
            .and_then(|guest_id| ctx.shadow_table.guest_object_version(guest_id))
            .is_some_and(|version| version >= zwp_linux_dmabuf_v1::REQ_GET_DEFAULT_FEEDBACK_SINCE)
        {
            return Action::Drop;
        }

        // if format == 0x34324241 || format == 0x34324258 {
        //     return Action::Drop;
        // }

        Action::Forward
    }

    fn on_modifier(
        ctx: &mut Context,
        sender: EventSender,
        format: u32,
        modifier_hi: u32,
        modifier_lo: u32,
    ) -> Action {
        let modifier = ((modifier_hi as u64) << 32) | (modifier_lo as u64);
        debug!(
            "Host advertises format: {:#010x}, modifier: {:#018x}",
            format, modifier
        );
        if !is_supported_drm_format(format) {
            return Action::Drop;
        }
        // We forward supported modifiers to the guest. The modifier itself is
        // intentionally preserved; LINEAR (0) is a valid modifier.
        if record_host_capability(ctx, sender.host, format, modifier) {
            return Action::Drop;
        }
        if sender
            .guest_id()
            .and_then(|guest_id| ctx.shadow_table.guest_object_version(guest_id))
            .is_some_and(|version| version >= zwp_linux_dmabuf_v1::REQ_GET_DEFAULT_FEEDBACK_SINCE)
        {
            return Action::Drop;
        }
        Action::Forward
    }
}

