/// The connection's dma-buf state that no one object owns
/// (`Context::dmabuf`). Its fields are this module's: only the
/// linux-dmabuf handlers read or write them. What one object keeps is in
/// its table entry: [`ParamsData`], [`DmabufFactory`], [`DmabufFeedback`].
#[derive(Debug, Default)]
pub(crate) struct Dmabuf {
    /// Capability snapshots for every host dmabuf global, by name, that
    /// anything holds ([`capabilities_held`]). A completed snapshot is
    /// immutable except for a defensive refresh if a non-conforming host
    /// sends a late unique pair.
    capabilities: BTreeMap<u32, DmabufCapabilityState>,
    /// The feedback objects refreshed in this dispatch batch. A host can
    /// advertise hundreds of pairs in a single roundtrip; sending one memfd
    /// per event can overflow the receiver's SCM_RIGHTS batch and
    /// desynchronize the Wayland FD stream, so each feedback is refreshed
    /// at most once a batch ([`Self::end_batch`]).
    refreshed: BTreeSet<GuestId>,
    /// Test-only capability override for exercising synthetic dma-buf
    /// feedback lifecycle without depending on the runner's `/dev/dri`.
    #[cfg(test)]
    feedback_available_for_test: bool,
}

impl Dmabuf {
    /// A dispatch batch ended: the next one may publish a newer table
    /// after more capabilities have arrived.
    pub(crate) fn end_batch(&mut self) {
        self.refreshed.clear();
    }

    /// Have the proxy synthesize feedback as if it had a virtio-gpu render
    /// node, which a test cannot have.
    #[cfg(test)]
    pub(crate) fn set_feedback_available_for_test(&mut self, available: bool) {
        self.feedback_available_for_test = available;
    }
}

#[derive(Debug, Default)]
struct DmabufCapabilityState {
    /// Legacy v3 format/modifier pairs collected for one host-global
    /// generation. The vector preserves the host's preference order while
    /// the linux-dmabuf handler rejects duplicate pairs.
    format_modifiers: Vec<(u32, u64)>,
    /// Set only after a host wl_display.sync callback proves that every
    /// format/modifier event generated by the internal v3 bind has arrived.
    ready: bool,
}

/// A guest `zwp_linux_buffer_params_v1`; its table entry keeps it.
#[derive(Debug)]
pub(crate) enum ParamsData {
    /// The planes added so far.
    Open(Vec<PendingParam>),
    /// A `create` or `create_immed` consumed the planes. The object stays
    /// alive, so later requests report `already_used`. An asynchronous
    /// `create` keeps what its `created` needs until the host answers.
    Used(Option<PendingNativeCreate>),
}

/// A plane a `zwp_linux_buffer_params_v1.add` gave, kept until the create
/// that sends it.
#[derive(Debug)]
pub(crate) struct PendingParam {
    pub(crate) fd: OwnedFd,
    pub(crate) plane_idx: u32,
    pub(crate) offset: u32,
    pub(crate) stride: u32,
    pub(crate) modifier_hi: u32,
    pub(crate) modifier_lo: u32,
}

/// What an asynchronous `create` keeps for the buffer its `created` makes.
/// The params object's entry holds it, so a late result can reach only
/// the object that asked for it.
#[derive(Debug)]
pub(crate) struct PendingNativeCreate {
    dimensions: (i32, i32),
    sync_fds: Vec<OwnedFd>,
}

/// A guest `zwp_linux_dmabuf_v1`; its table entry keeps it.
#[derive(Debug)]
pub(crate) struct DmabufFactory {
    /// The host global it was bound from. Global removal does not
    /// invalidate an already-bound factory.
    global: u32,
}

/// A synthetic guest `zwp_linux_dmabuf_feedback_v1`; its table entry keeps
/// it.
#[derive(Debug)]
pub(crate) struct DmabufFeedback {
    /// The host global whose capabilities it carries, so an object created
    /// from an old, still-bound factory stays isolated from a replacement
    /// global's capabilities.
    global: u32,
}

/// `DRM_FORMAT_MOD_INVALID` is the legacy implicit-modifier marker used by
/// the linux-dmabuf v3 format events. Keep this local instead of depending on
/// libdrm headers so the proxy remains buildable in the minimal Nix shell.
const DRM_FORMAT_MOD_INVALID: u64 = (1u64 << 56) - 1;
/// The newest `zwp_linux_dmabuf_v1` offered to guests: the version that
/// added the feedback objects, which the proxy synthesizes. v5 changes
/// tranche semantics that the proxy does not translate, so it is never
/// offered. A feedback object takes its factory's version, so it has this
/// one too.
pub(crate) const GUEST_DMABUF_VERSION: u32 = zwp_linux_dmabuf_v1::REQ_GET_DEFAULT_FEEDBACK_SINCE;
const MAX_FEEDBACK_FORMATS: usize = u16::MAX as usize + 1;
/// The most uint16 indices one `tranche_formats` event carries: the longest
/// message less its header and array length word, in whole 4-byte words.
const MAX_TRANCHE_INDICES_PER_EVENT: usize = (MessageHeader::MAX_LEN - MessageHeader::LEN - 4) / 2;

/// The virtio-gpu render node's `dev_t`, in native byte order, as the
/// feedback's `main_device` carries it.
fn local_device_id(ctx: &Context) -> io::Result<Vec<u8>> {
    let virtgpu = ctx.virtgpu().ok_or_else(|| {
        io::Error::new(
            io::ErrorKind::NotFound,
            "no virtio-gpu render node for synthetic dmabuf feedback",
        )
    })?;
    Ok(virtgpu.device_number()?.to_ne_bytes().to_vec())
}

/// The format and modifier pairs of host linux-dmabuf global `global`
/// that synthetic feedback offers.
fn feedback_pairs(ctx: &Context, global: u32) -> Vec<(u32, u64)> {
    let mut pairs = Vec::new();
    let mut seen = std::collections::BTreeSet::new();

    if let Some(capabilities) = ctx.dmabuf.capabilities.get(&global) {
        for &(format, modifier) in &capabilities.format_modifiers {
            if is_supported_drm_format(format)
                && seen.insert((format, modifier))
                && pairs.len() < MAX_FEEDBACK_FORMATS
            {
                pairs.push((format, modifier));
            }
        }
    }

    pairs
}

/// Whether every capability of host linux-dmabuf global `global` has
/// arrived.
pub(crate) fn capabilities_ready(ctx: &Context, global: u32) -> bool {
    ctx.dmabuf
        .capabilities
        .get(&global)
        .is_some_and(|capabilities| capabilities.ready)
}

pub(crate) fn has_synthetic_feedback_formats(ctx: &Context, global: u32) -> bool {
    !feedback_pairs(ctx, global).is_empty()
}

/// Drop the capabilities of host linux-dmabuf global `global` once nothing
/// holds them ([`capabilities_held`]).
pub(crate) fn maybe_reclaim_capabilities(ctx: &mut Context, global: u32) {
    if !capabilities_held(ctx, global) {
        ctx.dmabuf.capabilities.remove(&global);
    }
}

/// Whether anything still holds the capabilities of host linux-dmabuf
/// global `global`: the proxy's binding of it, a sync awaiting its formats,
/// a guest factory or synthetic feedback, or a guest global waiting for its
/// formats.
pub(crate) fn capabilities_held(ctx: &Context, global: u32) -> bool {
    host_dmabuf_global(ctx) == Some(global)
        || ctx.internal_callbacks.awaits_dmabuf_capabilities(global)
        || ctx
            .shadow_table
            .data_of::<DmabufFactory>()
            .any(|(_, factory)| factory.global == global)
        || ctx
            .shadow_table
            .data_of::<DmabufFeedback>()
            .any(|(_, feedback)| feedback.global == global)
        || ctx.globals.awaits_dmabuf_capabilities(global)
}

/// Panic if dma-buf capabilities outlived every hold on their global.
#[cfg(test)]
pub(crate) fn assert_no_orphans(ctx: &Context) {
    for &global in ctx.dmabuf.capabilities.keys() {
        assert!(
            capabilities_held(ctx, global),
            "dma-buf capabilities outlived every hold on global {global}"
        );
    }
}

/// The name of the host linux-dmabuf global the proxy has bound, whose
/// capabilities its binding collects.
fn host_dmabuf_global(ctx: &Context) -> Option<u32> {
    Some(ctx.globals.singletons().get(Singleton::Dmabuf)?.name)
}

fn create_feedback_format_table(pairs: &[(u32, u64)]) -> io::Result<(OwnedFd, u32)> {
    if pairs.is_empty() || pairs.len() > MAX_FEEDBACK_FORMATS {
        return Err(io::Error::new(
            io::ErrorKind::InvalidInput,
            "invalid synthetic feedback table length",
        ));
    }
    let size = pairs
        .len()
        .checked_mul(16)
        .ok_or_else(|| io::Error::new(io::ErrorKind::InvalidInput, "format table overflow"))?;
    let mut file = File::from(nix::sys::memfd::memfd_create(
        c"sommelier-dmabuf",
        MFdFlags::MFD_CLOEXEC | MFdFlags::MFD_ALLOW_SEALING,
    )?);
    file.set_len(size as u64)?;

    let mut table = Vec::with_capacity(size);
    for &(format, modifier) in pairs {
        table.extend_from_slice(&format.to_ne_bytes());
        table.extend_from_slice(&0u32.to_ne_bytes());
        table.extend_from_slice(&modifier.to_ne_bytes());
    }
    file.write_all(&table)?;
    let seals = libc::F_SEAL_SHRINK | libc::F_SEAL_GROW | libc::F_SEAL_WRITE | libc::F_SEAL_SEAL;
    if unsafe { libc::fcntl(file.as_raw_fd(), libc::F_ADD_SEALS, seals) } < 0 {
        return Err(io::Error::last_os_error());
    }
    Ok((file.into(), size as u32))
}

fn build_synthetic_feedback_messages(
    guest_id: GuestId,
    pairs: &[(u32, u64)],
    device: &[u8],
) -> io::Result<Vec<ToGuest>> {
    let (table, table_size) = create_feedback_format_table(pairs)?;
    // Only the array-carrying events can exceed the wire limit. They are
    // built before the table's event takes its descriptor, so a failure
    // closes the table with nothing queued.
    let too_large = |_| {
        io::Error::new(
            io::ErrorKind::InvalidData,
            "synthetic dmabuf feedback event exceeds Wayland wire limits",
        )
    };
    let main_device =
        zwp_linux_dmabuf_feedback_v1::evt::main_device(guest_id, device).map_err(too_large)?;
    let tranche_device = zwp_linux_dmabuf_feedback_v1::evt::tranche_target_device(guest_id, device)
        .map_err(too_large)?;
    let tranche_formats = (0..pairs.len())
        .step_by(MAX_TRANCHE_INDICES_PER_EVENT)
        .map(|start| {
            let end = pairs
                .len()
                .min(start.saturating_add(MAX_TRANCHE_INDICES_PER_EVENT));
            let mut bytes = Vec::with_capacity((end - start) * 2);
            for index in start..end {
                bytes.extend_from_slice(&(index as u16).to_ne_bytes());
            }
            zwp_linux_dmabuf_feedback_v1::evt::tranche_formats(guest_id, &bytes)
        })
        .collect::<Result<Vec<_>, _>>()
        .map_err(too_large)?;

    // The table is sent before the parameter sequence, matching existing
    // compositors and allowing every following tranche index to refer to it.
    let mut pending = vec![
        zwp_linux_dmabuf_feedback_v1::evt::format_table(guest_id, table, table_size),
        main_device,
        tranche_device,
        // No direct-scanout preference is known for a guest-side render
        // node; a zero flag is the conservative default tranche.
        zwp_linux_dmabuf_feedback_v1::evt::tranche_flags(guest_id, 0),
    ];
    pending.extend(tranche_formats);
    pending.extend([
        zwp_linux_dmabuf_feedback_v1::evt::tranche_done(guest_id),
        zwp_linux_dmabuf_feedback_v1::evt::done(guest_id),
    ]);
    Ok(pending)
}

fn dmabuf_plane_layout(format: u32, plane_idx: u32, width: i32, height: i32) -> Option<(u64, u64)> {
    let width = u64::try_from(width).ok()?;
    let height = u64::try_from(height).ok()?;
    match format {
        wl_shm::FORMAT_NV12 if width % 2 == 0 && height % 2 == 0 && plane_idx < 2 => {
            Some((width, if plane_idx == 0 { height } else { height / 2 }))
        }
        0x3631_4752 if plane_idx == 0 => Some((width.checked_mul(2)?, height)),
        0x3432_5258 | 0x3432_5241 | 0x3432_4258 | 0x3432_4241 if plane_idx == 0 => {
            Some((width.checked_mul(4)?, height))
        }
        _ => None,
    }
}

fn valid_dmabuf_plane(param: &PendingParam, format: u32, width: i32, height: i32) -> bool {
    let Some((minimum_row_bytes, rows)) =
        dmabuf_plane_layout(format, param.plane_idx, width, height)
    else {
        return false;
    };
    let stride = u64::from(param.stride);
    if stride < minimum_row_bytes {
        return false;
    }

    // The host compositor will evaluate offset + stride * (rows - 1) +
    // minimum_row_bytes while importing the plane. Check the same arithmetic
    // here so malformed metadata cannot wrap into a small in-bounds span.
    let Some(last_row_offset) = stride.checked_mul(rows.saturating_sub(1)) else {
        return false;
    };
    u64::from(param.offset)
        .checked_add(last_row_offset)
        .and_then(|end| end.checked_add(minimum_row_bytes))
        .is_some()
}

/// Reject the message for synthetic feedback the proxy could not allocate,
/// as libwayland's `wl_client_post_no_memory` does: the display's
/// `no_memory` error.
#[must_use = "a handler returns the Action::Drop"]
fn reject_unallocatable_feedback(ctx: &mut Context) -> Action {
    ctx.reject(
        GuestId::DISPLAY,
        wl_display::ERROR_NO_MEMORY,
        "unable to allocate linux-dmabuf feedback",
    )
}

fn queue_synthetic_feedback(ctx: &mut Context, guest_id: GuestId, global: u32) -> io::Result<()> {
    let pairs = feedback_pairs(ctx, global);
    let device = local_device_id(ctx)?;
    let pending = build_synthetic_feedback_messages(guest_id, &pairs, &device)?;

    // Publish a complete sequence atomically. A client must never observe a
    // new format_table without the matching done event.
    ctx.send_guest_all(pending);
    Ok(())
}

/// Create guest feedback `guest_id` of guest factory `factory_id`, which
/// the proxy serves itself.
fn create_synthetic_feedback(ctx: &mut Context, factory_id: GuestId, guest_id: GuestId) -> Action {
    let factory = ctx.shadow_table.data::<DmabufFactory>(factory_id);
    let Some(global) = factory.map(|factory| factory.global) else {
        // The factory interface declares no errors, and the client did
        // nothing wrong: the proxy lost its own bookkeeping.
        return ctx.fail(format_args!(
            "Cannot create synthetic dmabuf feedback for untracked factory {factory_id}"
        ));
    };
    ctx.shadow_table.create_local_with(
        guest_id,
        Iface::ZwpLinuxDmabufFeedbackV1,
        GUEST_DMABUF_VERSION,
        DmabufFeedback { global },
    );
    let ready = ctx
        .dmabuf
        .capabilities
        .get(&global)
        .is_some_and(|capabilities| capabilities.ready);
    if ready {
        if let Err(error) = queue_synthetic_feedback(ctx, guest_id, global) {
            log::error!("Failed to create synthetic dmabuf feedback of global {global}: {error}");
            return reject_unallocatable_feedback(ctx);
        }
    }
    Action::Drop
}

/// Every capability of host linux-dmabuf global `global` has arrived:
/// publish the guest globals and feedback that wait for them.
pub(crate) fn complete_capability_discovery(ctx: &mut Context, global: u32) {
    let Some(capabilities) = ctx.dmabuf.capabilities.get_mut(&global) else {
        log::warn!("Ignoring linux-dmabuf capability callback for unknown global {global}");
        return;
    };
    if capabilities.ready {
        return;
    }
    capabilities.ready = true;

    crate::handler::registry::publish_pending_dmabuf_globals(ctx, global);

    for guest_id in feedback_of(ctx, global) {
        if let Err(error) = queue_synthetic_feedback(ctx, guest_id, global) {
            log::error!("Failed to publish completed dmabuf feedback of global {global}: {error}");
            // Deep in a wl_callback.done: the session ends, and the
            // loop drops this message's effects whatever its handler
            // returns.
            let _ = reject_unallocatable_feedback(ctx);
            break;
        }
    }
}

/// Record supported `format` with `modifier` if `sender` is the proxy's
/// own linux-dmabuf binding, whose events reach no guest.
///
/// # Returns
///
/// Whether the sender is that binding.
fn record_host_capability(ctx: &mut Context, sender: HostId, format: u32, modifier: u64) -> bool {
    let Some(binding) = ctx.globals.singletons().get(Singleton::Dmabuf) else {
        return false;
    };
    if sender != binding.host {
        return false;
    }
    record_host_shm_drm_format(ctx, format);
    let capabilities = ctx.dmabuf.capabilities.entry(binding.name).or_default();
    if capabilities.format_modifiers.len() < MAX_FEEDBACK_FORMATS
        && !capabilities.format_modifiers.contains(&(format, modifier))
    {
        capabilities.format_modifiers.push((format, modifier));
        refresh_synthetic_feedbacks(ctx, binding.name);
    }
    true
}

/// The synthetic feedback objects that carry the capabilities of host
/// linux-dmabuf global `global`, in order.
fn feedback_of(ctx: &Context, global: u32) -> Vec<GuestId> {
    ctx.shadow_table
        .data_of::<DmabufFeedback>()
        .filter_map(|(guest_id, feedback)| (feedback.global == global).then_some(guest_id))
        .collect()
}

fn refresh_synthetic_feedbacks(ctx: &mut Context, global: u32) {
    if !ctx
        .dmabuf
        .capabilities
        .get(&global)
        .is_some_and(|capabilities| capabilities.ready)
    {
        return;
    }
    for guest_id in feedback_of(ctx, global) {
        // Legacy dmabuf capabilities arrive as one format event followed
        // by many modifier events. Queue at most one replacement per
        // proxy dispatch batch; otherwise every event creates another
        // memfd-bearing format_table message and a large host roundtrip
        // can exceed the receiver's SCM_RIGHTS capacity.
        if !ctx.dmabuf.refreshed.insert(guest_id) {
            continue;
        }
        if let Err(error) = queue_synthetic_feedback(ctx, guest_id, global) {
            log::error!("Failed to refresh synthetic dmabuf feedback of global {global}: {error}");
            ctx.dmabuf.refreshed.remove(&guest_id);
            // Deep in a capability event: the session ends, and the
            // loop drops this message's effects whatever its handler
            // returns.
            let _ = reject_unallocatable_feedback(ctx);
            break;
        }
    }
}

/// The planes of params `params_id`, while no create has used them.
fn open_params(ctx: &Context, params_id: GuestId) -> Option<&[PendingParam]> {
    match ctx.shadow_table.data::<ParamsData>(params_id)? {
        ParamsData::Open(params) => Some(params),
        ParamsData::Used(_) => None,
    }
}

/// Take what the asynchronous create of live params `params_id` keeps for
/// its `created`, if it waits for one.
fn take_native_create(ctx: &mut Context, params_id: GuestId) -> Option<PendingNativeCreate> {
    match ctx.shadow_table.data_mut::<ParamsData>(params_id)? {
        ParamsData::Used(create) => create.take(),
        ParamsData::Open(_) => None,
    }
}

/// Whether a create has used params `params_id`.
fn params_used(ctx: &Context, params_id: GuestId) -> bool {
    matches!(
        ctx.shadow_table.data::<ParamsData>(params_id),
        Some(ParamsData::Used(_))
    )
}

/// Queue the ADDs of params `params_id` and mark it used, keeping `create`
/// for an asynchronous one. Returns its host ID and the planes'
/// synchronization descriptors, or the action a handler returns when it
/// cannot.
fn process_params(ctx: &mut Context, params_id: GuestId) -> Result<(HostId, Vec<OwnedFd>), Action> {
    let params = match ctx.shadow_table.data_mut::<ParamsData>(params_id) {
        Some(data @ ParamsData::Open(_)) => match std::mem::replace(data, ParamsData::Used(None)) {
            ParamsData::Open(params) => params,
            ParamsData::Used(_) => unreachable!("the params were open"),
        },
        _ => return Err(Action::Drop),
    };
    let Some(host_id) = ctx.shadow_table.get_host_id(params_id) else {
        // The guest request was valid when it entered the proxy, so a
        // missing host mapping is an internal state corruption rather
        // than a recoverable client error. Do not let callers continue
        // with a CREATE that has no corresponding host params object.
        return Err(ctx.fail(format_args!("Unknown host ID for params {params_id}")));
    };

    // Keep one descriptor for every plane. Multi-plane formats may use
    // separate dma-buf objects, so waiting only plane zero can present
    // plane-one GPU writes before they complete. Inode identity proves
    // two descriptors are the same dma-buf only from Linux 5.3, where
    // each dma-buf has its own inode, while an extra wait on shared
    // backing is harmless.
    // The queued ADD owns the original descriptor while these duplicates
    // live with the render-buffer generation through its final destroy.
    let mut sync_fds = Vec::new();
    for param in &params {
        match param.fd.try_clone() {
            Ok(sync_fd) => sync_fds.push(sync_fd),
            Err(error) => {
                return Err(ctx.fail(format_args!(
                    "Failed to duplicate dma-buf fd for synchronization: {error}"
                )));
            }
        }
    }
    if sync_fds.is_empty() {
        return Err(ctx.fail(format_args!("Params {params_id} have no planes to create")));
    }

    // Send the ADDs, each handing its descriptor to the queue. The caller
    // queues its CREATE right after.
    for param in params {
        // The guest's metadata, with `on_add`'s plane-0 fix-up.
        ctx.send_host(zwp_linux_buffer_params_v1::req::add(
            host_id,
            param.fd,
            param.plane_idx,
            param.offset,
            param.stride,
            param.modifier_hi,
            param.modifier_lo,
        ));
    }
    Ok((host_id, sync_fds))
}

fn valid_params(ctx: &Context, params_id: GuestId, width: i32, height: i32, format: u32) -> bool {
    if width <= 0 || height <= 0 || !is_supported_drm_format(format) {
        return false;
    }

    let Some(params) = open_params(ctx, params_id) else {
        return false;
    };
    let expected_planes: u32 = if format == wl_shm::FORMAT_NV12 { 2 } else { 1 }; // DRM_FORMAT_NV12
    if params.len() != expected_planes as usize {
        return false;
    }

    let mut seen_planes = std::collections::BTreeSet::new();
    params.iter().all(|param| {
        param.plane_idx < expected_planes
            && seen_planes.insert(param.plane_idx)
            && valid_dmabuf_plane(param, format, width, height)
    })
}

fn params_error_code(
    ctx: &Context,
    params_id: GuestId,
    width: i32,
    height: i32,
    format: u32,
) -> u32 {
    if width <= 0 || height <= 0 {
        return zwp_linux_buffer_params_v1::ERROR_INVALID_DIMENSIONS;
    }
    if !is_supported_drm_format(format) {
        return zwp_linux_buffer_params_v1::ERROR_INVALID_FORMAT;
    }
    let expected_planes = if format == wl_shm::FORMAT_NV12 { 2 } else { 1 };
    let Some(params) = open_params(ctx, params_id) else {
        return zwp_linux_buffer_params_v1::ERROR_INCOMPLETE;
    };
    if params.len() != expected_planes {
        return zwp_linux_buffer_params_v1::ERROR_INCOMPLETE;
    }
    let mut seen = std::collections::BTreeSet::new();
    for param in params {
        if param.plane_idx >= expected_planes as u32 {
            return zwp_linux_buffer_params_v1::ERROR_PLANE_IDX;
        }
        if !seen.insert(param.plane_idx) {
            return zwp_linux_buffer_params_v1::ERROR_PLANE_SET;
        }
        if !valid_dmabuf_plane(param, format, width, height) {
            return zwp_linux_buffer_params_v1::ERROR_OUT_OF_BOUNDS;
        }
    }
    zwp_linux_buffer_params_v1::ERROR_INCOMPLETE
}

